// プレイヤーキャラのIDを返す
export function getPlayerDef() {
  return CHARACTER_DEFS.find(c => c.isPlayer);
}

// 登場済みキャラ一覧
export function getUnlockedDefs() {
  return CHARACTER_DEFS.filter(c => c.unlocked);
}

// プレイヤーを切り替える（旧プレイヤーはNPCに、新プレイヤーはPlayerに）
export function switchPlayer(newPlayerId) {
  CHARACTER_DEFS.forEach(c => { c.isPlayer = (c.id === newPlayerId); });
}

// キャラをアンロック
export function unlockCharacter(id) {
  const def = CHARACTER_DEFS.find(c => c.id === id);
  if (def) def.unlocked = true;
}
